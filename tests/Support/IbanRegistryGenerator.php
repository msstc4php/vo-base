<?php

declare(strict_types=1);

namespace MSSTC4PHP\ValueObject\Tests\Support;

use RuntimeException;

/**
 * Renders src/Support/IbanRegistry.php from the TXT edition of the SWIFT IBAN Registry (docs/sources/IBAN.md):
 * a tab-separated table with one row per data element and one column per country. Only structural facts are
 * read (length, BBAN structure, identifier positions, SEPA flag); the registry's text is not redistributed.
 */
final class IbanRegistryGenerator
{
    private const array TYPE_CLASSES = ['n' => '[0-9]', 'a' => '[A-Z]', 'c' => '[A-Z0-9]'];

    /**
     * @param non-empty-string $edition identifies the TXT edition the facts come from
     */
    public function render(string $registryTxt, string $edition): string
    {
        $rows = $this->rows($registryTxt);

        $arms = '';
        foreach ($this->countries($rows) as $code => $country) {
            $arms .= \sprintf("            '%s' => new IbanFormat(%s),\n", $code, $country);
        }

        return \sprintf(
            <<<'PHP_WRAP'
            <?php
            
            declare(strict_types=1);
            
            namespace MSSTC4PHP\ValueObject\Support;
            
            /**
             * Generated by tools/generate-iban-registry.php from the SWIFT IBAN Registry (docs/sources/IBAN.md). Do not edit.
             * Edition: %s
             * Source SHA-256: %s.
             *
             * @internal
             */
            final class IbanRegistry
            {
                public static function find(string $countryCode): ?IbanFormat
                {
                    return match ($countryCode) {
            %s            default => null,
                    };
                }
            }
            
            PHP_WRAP,
            \str_replace('*/', '* /', $edition),
            \hash('sha256', $registryTxt),
            $arms,
        );
    }

    /**
     * @return array<string, list<string>> data element => cells, keyed by the first row carrying that label
     */
    private function rows(string $registryTxt): array
    {
        $stream = \fopen('php://memory', 'r+');
        if ($stream === false) {
            throw new RuntimeException('Cannot open a memory stream.');
        }
        \fwrite($stream, $registryTxt);
        \rewind($stream);

        $rows = [];
        while (($cells = \fgetcsv($stream, null, "\t", '"', '')) !== false) {
            $label = \trim((string) $cells[0]);
            if ($label === '' || isset($rows[$label])) {
                continue;
            }

            $rows[$label] = \array_map(static fn (?string $cell): string => \trim((string) $cell), \array_slice($cells, 1));
        }
        \fclose($stream);

        return $rows;
    }

    /**
     * @param array<string, list<string>> $rows
     *
     * @return array<string, string> country code => constructor arguments
     */
    private function countries(array $rows): array
    {
        $codes = $this->row($rows, 'IBAN prefix country code (ISO 3166)');

        $countries = [];
        foreach ($codes as $index => $code) {
            if (\preg_match('/^[A-Z]{2}$/D', $code) !== 1) {
                throw new RuntimeException(\sprintf('Column %d has no country code.', $index));
            }
            if (isset($countries[$code])) {
                throw new RuntimeException(\sprintf('Country %s is listed twice.', $code));
            }

            $countries[$code] = $this->country($rows, $index, $code);
        }

        \ksort($countries);

        return $countries;
    }

    /**
     * @param array<string, list<string>> $rows
     */
    private function country(array $rows, int $index, string $code): string
    {
        $cell = fn (string $label): string => $this->row($rows, $label)[$index] ?? '';

        $structure = $cell('BBAN structure');
        $bbanLength = (int) $cell('BBAN length');
        $ibanLength = (int) $cell('IBAN length');
        $pattern = $this->pattern($structure, $bbanLength, $code);
        if ($ibanLength !== $bbanLength + 4 || $ibanLength < 15 || $ibanLength > 34) {
            throw new RuntimeException(\sprintf('%s: IBAN length %d does not fit BBAN length %d.', $code, $ibanLength, $bbanLength));
        }

        [$bankStart, $bankLength] = $this->position($cell('Bank identifier position within the BBAN'), $bbanLength, $code);
        $branch = $this->optionalPosition($cell('Branch identifier position within the BBAN'), $bbanLength, $code);

        $sepa = match ($cell('SEPA country')) {
            'Yes' => 'true',
            'No' => 'false',
            default => throw new RuntimeException(\sprintf('%s: the SEPA flag is neither Yes nor No.', $code)),
        };

        $example = $cell('IBAN electronic format example');
        if (\strlen($example) !== $ibanLength || !\str_starts_with($example, $code) || \preg_match($pattern, \substr($example, 4)) !== 1) {
            throw new RuntimeException(\sprintf('%s: the registry example does not fit the registry structure.', $code));
        }

        return \sprintf(
            "length: %d, bbanPattern: '%s', bankStart: %d, bankLength: %d, sepa: %s%s",
            $ibanLength,
            $pattern,
            $bankStart,
            $bankLength,
            $sepa,
            $branch === null ? '' : \sprintf(', branchStart: %d, branchLength: %d', $branch[0], $branch[1]),
        );
    }

    /**
     * @param array<string, list<string>> $rows
     *
     * @return list<string>
     */
    private function row(array $rows, string $label): array
    {
        return $rows[$label] ?? throw new RuntimeException(\sprintf('The registry has no "%s" row.', $label));
    }

    private function pattern(string $structure, int $bbanLength, string $code): string
    {
        if (\preg_match_all('/(\d+)!([nac])/', $structure, $parts, \PREG_SET_ORDER) === 0
            || \implode('', \array_column($parts, 0)) !== $structure) {
            throw new RuntimeException(\sprintf('%s: unreadable BBAN structure "%s".', $code, $structure));
        }

        $pattern = '';
        $total = 0;
        foreach ($parts as $part) {
            $pattern .= \sprintf('%s{%d}', self::TYPE_CLASSES[$part[2]], $part[1]);
            $total += (int) $part[1];
        }
        if ($total !== $bbanLength) {
            throw new RuntimeException(\sprintf('%s: BBAN structure "%s" is not %d characters long.', $code, $structure, $bbanLength));
        }

        return '/^' . $pattern . '$/D';
    }

    /**
     * @return array{non-negative-int, int}|null
     */
    private function optionalPosition(string $position, int $bbanLength, string $code): ?array
    {
        return $position === '' || $position === 'N/A' ? null : $this->position($position, $bbanLength, $code);
    }

    /**
     * @return array{non-negative-int, int} zero-based start and length, from the registry's one-based "from-to"
     */
    private function position(string $position, int $bbanLength, string $code): array
    {
        if (\preg_match('/^(\d+)-(\d+)$/D', $position, $matches) !== 1) {
            throw new RuntimeException(\sprintf('%s: unreadable identifier position "%s".', $code, $position));
        }

        $from = (int) $matches[1];
        $to = (int) $matches[2];
        if ($from < 1 || $to < $from || $to > $bbanLength) {
            throw new RuntimeException(\sprintf('%s: identifier position "%s" lies outside the BBAN.', $code, $position));
        }

        return [$from - 1, $to - $from + 1];
    }
}
